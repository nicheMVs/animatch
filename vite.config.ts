import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

export default defineConfig(async ({ command }) => {
  const plugins: any[] = [react(), tailwindcss()];

  // Load the dev-only source writer plugin ONLY during `npm run dev`.
  // Vercel runs `vite build`, so this branch is never executed there.
  if (command === 'serve') {
    const fs = await import('node:fs');
    const path = await import('node:path');
    const { fileURLToPath } = await import('node:url');
    const __filename = fileURLToPath(import.meta.url);
    const __dirname = path.dirname(__filename);
    const CONFIG_PATH = path.resolve(__dirname, 'src/config/sourceDefaults.ts');

    plugins.push({
      name: 'dev-source-writer',
      apply: 'serve',
      configureServer(server: any) {
        server.middlewares.use('/__dev/save-source-defaults', (req: any, res: any) => {
          if (req.method !== 'POST') {
            res.statusCode = 405;
            res.end('Method not allowed');
            return;
          }
          let body = '';
          req.on('data', (chunk: any) => (body += chunk));
          req.on('end', () => {
            try {
              const data = JSON.parse(body);
              const { includeTags, excludeTags, rating } = data;
              if (
                typeof includeTags !== 'string' ||
                typeof excludeTags !== 'string' ||
                typeof rating !== 'string'
              ) {
                res.statusCode = 400;
                res.end('Invalid payload');
                return;
              }
              const fileContents = `// AUTO-GENERATED BY DEV PANEL. Edit tags via the in-app dev panel, not here.
// This file ships with the production build. Whatever is here is what everyone sees.

export interface SourceDefaults {
  includeTags: string;
  excludeTags: string;
  rating: string;
}

export const SOURCE_DEFAULTS: Record<string, SourceDefaults> = {
  danbooru: {
    includeTags: ${JSON.stringify(includeTags)},
    excludeTags: ${JSON.stringify(excludeTags)},
    rating: ${JSON.stringify(rating)},
  },
};
`;
              fs.writeFileSync(CONFIG_PATH, fileContents, 'utf-8');
              res.setHeader('Content-Type', 'application/json');
              res.end(JSON.stringify({ ok: true }));
            } catch (err: any) {
              res.statusCode = 500;
              res.end(JSON.stringify({ error: err.message }));
            }
          });
        });
      },
    });
  }

  return {
    plugins,
    server: {
      host: true,
      proxy: {
        '/api': {
          target: 'https://animatch-tawny.vercel.app',
          changeOrigin: true,
          secure: true,
        },
      },
    },
  };
});